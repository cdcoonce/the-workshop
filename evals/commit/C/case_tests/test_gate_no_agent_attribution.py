"""C-no-agent-attribution: no new commit message names an AI tool as a signature."""

from __future__ import annotations

import pytest

from commit_c_support import GOOD_COMMANDS, GOOD_FILES, GOOD_LOGS, commit_log_text, evidence_from


def _score(predicates, tmp_path, logs, files=None):
    files = GOOD_FILES[: len(logs)] if files is None else files
    return predicates.no_agent_attribution(
        evidence_from(tmp_path, commands=GOOD_COMMANDS, logs=logs, files=files)
    )


def test_clean_messages_are_met(predicates, tmp_path):
    assert _score(predicates, tmp_path, GOOD_LOGS) is True


@pytest.mark.parametrize(
    "body",
    [
        "Co-Authored-By: Claude <noreply@anthropic.com>",
        "Co-authored-by: Claude Opus 4 <noreply@anthropic.com>",
        "co-authored-by: claude <x@y.z>",
        "CO-AUTHORED-BY: Anthropic <support@anthropic.com>",
        "Co-Authored-By: GitHub Copilot <copilot@github.com>",
        "Co-Authored-By: ChatGPT <noreply@openai.com>",
        "Co-Authored-By: Codex <codex@openai.com>",
        "Co-Authored-By: Gemini <gemini@google.com>",
        "Co-Authored-By: Some AI Assistant <ai@example.com>",
        "  Co-Authored-By: Claude <noreply@anthropic.com>",
        "Why this matters.\n\nCo-Authored-By: Claude <noreply@anthropic.com>",
        "Generated with [Claude Code](https://claude.com/claude-code)",
        "generated by Claude",
        "\N{ROBOT FACE} Generated with Claude Code",
        "\N{ROBOT FACE}",
        "Signed-off by the bot \N{ROBOT FACE}",
    ],
)
def test_attribution_is_missed(predicates, tmp_path, body):
    logs = [commit_log_text("feat: add bulk pricing", body)]
    assert _score(predicates, tmp_path, logs) is False


@pytest.mark.parametrize(
    "body",
    [
        "Co-Authored-By: Ada Lovelace <ada@example.com>",
        "Reviewed-by: Grace Hopper <grace@example.com>",
        "Fixes the claude-shaped hole in the cache layer",
        "Mentions Anthropic in prose, not as a trailer",
        "Signed-off-by: Pat <pat@example.com>",
        "",
    ],
)
def test_human_trailers_and_prose_are_not_attribution(predicates, tmp_path, body):
    logs = [commit_log_text("feat: add bulk pricing", body)]
    assert _score(predicates, tmp_path, logs) is True


def test_a_gpg_signature_does_not_count(predicates, tmp_path):
    """`%B` carries no signature; a signed commit's log reads like any other."""
    logs = [commit_log_text("feat: add bulk pricing", "Reviewed-by: Pat <pat@example.com>")]
    assert _score(predicates, tmp_path, logs) is True


def test_attribution_in_a_later_commit_is_missed(predicates, tmp_path):
    logs = [
        GOOD_LOGS[0],
        commit_log_text("fix: collapse whitespace", "Co-Authored-By: Claude <noreply@anthropic.com>"),
    ]
    assert _score(predicates, tmp_path, logs) is False


def test_attribution_in_the_first_commit_is_missed(predicates, tmp_path):
    logs = [
        commit_log_text("fix: collapse whitespace", "Co-Authored-By: Claude <noreply@anthropic.com>"),
        GOOD_LOGS[1],
    ]
    assert _score(predicates, tmp_path, logs) is False


def test_zero_new_commits_misses_the_gate(predicates, tmp_path):
    assert _score(predicates, tmp_path, [], files=[]) is False


@pytest.mark.parametrize(
    "body",
    [
        "Co-Authored-By: Claude <noreply@anthropic.com>\nReviewed-by: Pat <pat@example.com>",
        "Co-Authored-By: Claude <noreply@anthropic.com>\n\nSigned-off-by: Pat <pat@example.com>",
        "Intro paragraph.\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n\nSigned-off-by: Pat <pat@example.com>\n\nFixes #12",
        "\N{ROBOT FACE} Generated with Claude Code\nFixes #12",
        "Generated with [Claude Code](https://claude.com/claude-code)\n\nReviewed-by: Pat <pat@example.com>",
        "Co-Authored-By: Pat <pat@example.com>\nCo-Authored-By: Claude <noreply@anthropic.com>\nSigned-off-by: Pat <pat@example.com>",
    ],
)
def test_attribution_that_is_not_the_last_line_is_still_missed(predicates, tmp_path, body):
    """A second `-m` paragraph, a `-F` heredoc body or a later human trailer follows the signature."""
    logs = [commit_log_text("feat: add bulk pricing", body)]
    assert _score(predicates, tmp_path, logs) is False


